import React from 'react';
import { cn } from '../../utils/cn';

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  hoverEffect?: boolean;
}

export const Card = React.forwardRef<HTMLDivElement, CardProps>(
  ({ className, hoverEffect, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        'rounded-xl border border-[#E1DBEA] bg-white text-[#292238] shadow-[0_2px_12px_rgba(49,35,75,0.06)] transition-all duration-150',
        hoverEffect && 'hover:shadow-[0_4px_16px_rgba(49,35,75,0.10)] hover:border-[#DCD5E8]',
        className
      )}
      {...props}
    />
  )
);
Card.displayName = 'Card';

export const CardHeader = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div ref={ref} className={cn('flex flex-col space-y-1.5 p-5 border-b border-[#E1DBEA]', className)} {...props} />
  )
);
CardHeader.displayName = 'CardHeader';

