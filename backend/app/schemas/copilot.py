from datetime import date, datetime
from typing import Optional, List, Dict, Any, Literal
from pydantic import BaseModel, Field, ConfigDict


# ---------------------------------------------------------------------------
# Copilot Chat Models
# ---------------------------------------------------------------------------
class CopilotChatRequest(BaseModel):
    message: str = Field(..., min_length=1, max_length=2000, description="HR operational query or instruction")
    conversation_id: Optional[str] = Field(default=None, description="Optional existing session/conversation ID")


class RecordCitation(BaseModel):
    id: str = Field(..., description="Unique record reference string, e.g. 'task-3268', 'emp-102'")
    entity_type: str = Field(..., description="TASK, EMPLOYEE, ONBOARDING, PROBATION, CONFIRMATION, DOCUMENT, PERFORMANCE, OFFBOARDING, FOLLOWUP, ESCALATION")
    entity_id: int = Field(..., description="Database numeric primary key")
    title: str = Field(..., description="Display title or name of the record")
    subtitle: Optional[str] = Field(default=None, description="Contextual info like department or stage")
    status: Optional[str] = Field(default=None, description="Official database status")
    link_path: str = Field(..., description="Target frontend route URL to view or act on the record")

    model_config = ConfigDict(from_attributes=True)


class SourceMetadata(BaseModel):
    tools_called: List[str] = Field(default_factory=list, description="Names of tools executed against HR database")
    data_as_of: str = Field(..., description="Operational date timestamp of retrieved records")
    model_used: str = Field(..., description="Configured LLM model or deterministic engine version")
    is_ai_generated: bool = Field(..., description="True if generated by live LLM, False if deterministic fallback")
    response_status: str = Field(..., description="SUCCESS, OFFLINE_FALLBACK, AI_SERVICE_UNAVAILABLE, ERROR")
    execution_time_seconds: float = Field(default=0.0, description="Roundtrip processing time in seconds")


class CopilotChatResponse(BaseModel):
    conversation_id: str
    assistant_message: str
    response_status: Literal["SUCCESS", "OFFLINE_FALLBACK", "AI_SERVICE_UNAVAILABLE", "ERROR"]
    related_records: List[RecordCitation] = Field(default_factory=list)
    source_metadata: SourceMetadata
    suggested_next_actions: List[str] = Field(default_factory=list)
    generated_at: str


# ---------------------------------------------------------------------------
# Daily Briefing Models
# ---------------------------------------------------------------------------
class DailyBriefingKeyUpdate(BaseModel):
    category: str = Field(..., description="Process or operational category, e.g. 'Task Management', 'Probation'")
    headline: str = Field(..., description="Concise statement with verified counts and facts")
    description: str = Field(..., description="Contextual explanation of required next action")
    severity: Literal["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"] = "INFO"
    action_label: str = Field(default="View Details", description="Button text for quick navigation")
    link_path: str = Field(..., description="Target frontend path")
    record_id: Optional[str] = None


class HRDailyBriefingResponse(BaseModel):
    opening_summary: str = Field(..., description="Concise greeting and high-level operational status")
    key_updates: List[DailyBriefingKeyUpdate] = Field(default_factory=list, description="Maximum 3-5 concise updates")
    recommended_focus: str = Field(..., description="Direct operational recommendation for priority order")
    generated_at: str
    data_as_of: str
    is_ai_generated: bool
    source_status: Literal["AI_GENERATED", "DETERMINISTIC_FALLBACK"]


# ---------------------------------------------------------------------------
# Suggested Prompts
# ---------------------------------------------------------------------------
class SuggestedPromptItem(BaseModel):
    id: str
    title: str
    prompt: str
    category: str
